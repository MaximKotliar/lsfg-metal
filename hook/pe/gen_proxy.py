#!/usr/bin/env python3
"""Generate a forwarding proxy DLL (C source) for a system DLL.

The proxy goes in a game's folder. Every export jumps straight to the real system DLL,
and on load it also loads lsfghook.dll, which brings the native hook into the game.
Usage: gen_proxy.py NAME OUT.c
"""
import sys

EXPORTS = {
    "version": """GetFileVersionInfoA GetFileVersionInfoByHandle GetFileVersionInfoExA GetFileVersionInfoExW
        GetFileVersionInfoSizeA GetFileVersionInfoSizeExA GetFileVersionInfoSizeExW GetFileVersionInfoSizeW
        GetFileVersionInfoW VerFindFileA VerFindFileW VerInstallFileA VerInstallFileW VerLanguageNameA
        VerLanguageNameW VerQueryValueA VerQueryValueW""",
    "dinput8": """DirectInput8Create DllCanUnloadNow DllGetClassObject DllRegisterServer DllUnregisterServer
        GetdfDIJoystick""",
}

name, out = sys.argv[1], sys.argv[2]
names = EXPORTS[name].split()
table = ",\n    ".join(f'"{n}"' for n in names)
thunks = "\n".join(f"THUNK({i}, {n})" for i, n in enumerate(names))
open(out, "w").write(f"""// Generated by gen_proxy.py: {name}.dll proxy for a game's folder.
// Forwards every export to the system {name}.dll and loads lsfghook.dll.
// Delete this file from the game folder to switch lsfg-metal off for that game.
#include "win.h"

#define COUNT {len(names)}
static const char *const names[COUNT] = {{
    {table}
}};
void *lsfg_real[COUNT]; // resolved targets, read by the jump stubs

// Each export is an indirect jump through lsfg_real[i], so arguments pass through untouched.
#define THUNK(i, name) \\
    __asm__(".globl " #name "\\n" #name ":\\n jmpq *lsfg_real+8*" #i "(%rip)\\n"); \\
    __asm__(".section .drectve\\n.ascii \\" -export:" #name "\\"\\n.text\\n");
{thunks}

BOOL WINAPI DllMain(HMODULE self, DWORD reason, LPVOID reserved) {{
    (void)reserved;
    if (reason != DLL_PROCESS_ATTACH) return 1;
    HMODULE real = LoadLibraryW(L"C:\\\\windows\\\\system32\\\\{name}.dll");
    if (!real || real == self) return 0; // would forward to ourselves: refuse to load
    for (int i = 0; i < COUNT; i++) lsfg_real[i] = (void *)GetProcAddress(real, names[i]);
    LoadLibraryW(L"lsfghook.dll"); // optional: the game runs normally if the hook is missing
    return 1;
}}
""")
